const kinds = ["expense", "income", "remittance"];
const app = "OpenAA Life Ledger";
const maxBytes = 5 * 1024 * 1024;
function check(ok, message) {
  if (!ok) throw new Error(message);
}
function key(kind) {
  check(kinds.includes(kind), "未知账本。");
  return "openaa_life_ledger_v1_" + kind;
}
function nonnegative(value, digits, label) {
  check(
    typeof value === "number" || (typeof value === "string" && value.trim()),
    "请输入" + label,
  );
  const n = Number(value);
  const scaled = Math.round((n + Number.EPSILON) * 10 ** digits);
  check(Number.isSafeInteger(scaled) && scaled >= 0, label + "必须是有效非负数。");
  return scaled / 10 ** digits;
}
export function normalize(kind, r) {
  key(kind);
  const date = r?.date;
  const parsed = new Date(date + "T12:00:00Z");
  check(
    /^\d{4}-\d{2}-\d{2}$/.test(date) &&
      Number.isFinite(+parsed) &&
      parsed.toISOString().slice(0, 10) === date,
    "请输入有效日期。",
  );
  const id = String(r.id ?? crypto.randomUUID());
  check(id.length > 0 && id.length <= 200, "记录编号无效。");
  const note = r.note ?? "";
  check(typeof note === "string" && note.length <= 10000, "备注格式不正确。");
  const fx = kind === "remittance";
  const deduct = fx && (r.type === "subtract" || Number(r.amount) < 0);
  const sign = deduct ? -1 : 1;
  const magnitude = value => {
    check(["number","string"].includes(typeof value) && String(value).trim(), "金额无效。");
    return Math.abs(Number(value));
  };
  const row = { id, date, amount: sign * nonnegative(fx ? magnitude(r.amount) : r.amount, 2, "美元金额"), note };
  if (typeof r.createdAt === "string") row.createdAt = r.createdAt;
  if (deduct) row.type = "subtract";
  if (kind === "remittance") {
    nonnegative(r.rate, 8, "汇率");
    row.rate = Number(r.rate);
    check(deduct || Number(r.cny) >= 0, "人民币金额方向不一致。");
    row.cny = sign * nonnegative(magnitude(r.cny), 2, "人民币金额");
  } else {
    check(["cash", "card"].includes(r.method), "请选择现金或银行卡。");
    row.method = r.method;
    if (kind === "expense") {
      check(
        typeof r.category === "string" &&
          r.category.trim() &&
          r.category.length <= 100,
        "请选择开支分类。",
      );
      row.category = r.category;
    }
  }
  return row;
}
export function totals(kind, rows) {
  key(kind);
  let usd = 0,
    cny = 0,
    cash = 0,
    card = 0, grossUsd = 0, grossCny = 0;
  for (const row of rows) {
    const cents = Math.round(row.amount * 100);
    usd += cents;
    if (row.method === "cash") cash += cents;
    if (row.method === "card") card += cents;
    if (kind === "remittance") {
      const yuan = Math.round(row.cny * 100);
      cny += yuan;
      grossUsd += Math.abs(cents);
      grossCny += Math.abs(yuan);
    }
  }
  return {
    usd: usd / 100,
    cny: cny / 100,
    cash: cash / 100,
    card: card / 100,
    count: rows.length,
    rate: grossUsd ? grossCny / grossUsd : 0,
  };
}
function checked(kind, records) {
  check(
    Array.isArray(records) && records.length <= 10000,
    "每本账最多 10000 条记录。",
  );
  const rows = records.map((r) => {
    check(r?.id != null, "记录缺少编号。");
    return normalize(kind, r);
  });
  check(new Set(rows.map((r) => r.id)).size === rows.length, "记录编号重复。");
  return rows;
}
export function backup(kind, rows) {
  const data = {
    app,
    version: 1,
    kind,
    exportedAt: new Date().toISOString(),
    records: checked(kind, rows),
  };
  check(new Blob([JSON.stringify(data)]).size <= maxBytes, "备份超过 5 MB。");
  return data;
}
export function restorableBooks() {
  return kinds.filter(k => localStorage.getItem(key(k) + "_before_import") !== null);
}
export function mergeRows(existing, incoming) {
  const incomingIds = new Set(incoming.map((row) => row.id));
  const existingIds = new Set(existing.map((row) => row.id));
  // Include identifiers generated by older releases for ID-less legacy rows.
  const generated = (id) => /^legacy-(auto-|(?:expense|remittance)-\d+-\d{4}-\d{2}-\d{2}$)/.test(id);
  const signature = (r) => JSON.stringify([
    r.date, r.amount, r.note, r.method, r.category, r.rate, r.cny, r.usd, r.payment, r.type,
  ]);
  const unmatched = new Map();
  for (const row of existing) {
    if (!generated(row.id) || incomingIds.has(row.id)) continue;
    const key = signature(row);
    unmatched.set(key, (unmatched.get(key) || 0) + 1);
  }
  const result = [...existing];
  for (const row of incoming) {
    if (existingIds.has(row.id)) continue;
    const key = signature(row);
    const count = unmatched.get(key) || 0;
    if (generated(row.id) && count) unmatched.set(key, count - 1);
    else result.push(row);
  }
  return result;
}
export function load(kind) {
  const raw = localStorage.getItem(key(kind));
  try {
    return raw === null ? [] : checked(kind, JSON.parse(raw));
  } catch (cause) {
    throw Object.assign(new Error("账本记录读取失败"), { kind, raw, cause });
  }
}
export function save(kind, rows) {
  const records = backup(kind, rows).records;
  localStorage.setItem(key(kind), JSON.stringify(records));
  return records;
}
export function importRows(kind, rows, mode = "merge") {
  check(["merge", "replace"].includes(mode), "请选择合并或覆盖。");
  const old = load(kind);
  const next = mode === "merge" ? mergeRows(old, rows) : rows;
  const normalized = backup(kind, next).records;
  if (JSON.stringify(old) === JSON.stringify(normalized)) return old;
  const snap = key(kind) + "_before_import";
  const prior = localStorage.getItem(snap);
  localStorage.setItem(snap, JSON.stringify(old));
  try {
    return save(kind, normalized);
  } catch (e) {
    if (prior === null) localStorage.removeItem(snap);
    else localStorage.setItem(snap, prior);
    throw e;
  }
}
export function restore(kind) {
  const snap = key(kind) + "_before_import";
  const raw = localStorage.getItem(snap);
  check(raw !== null, "没有可恢复的导入前记录。");
  const result = save(kind, JSON.parse(raw));
  localStorage.removeItem(snap);
  return result;
}
function mapBooks(fn) {
  return Object.fromEntries(kinds.map((kind) => [kind, fn(kind)]));
}
export function readBooks() {
  return mapBooks(load);
}
export function balances(books) {
  const { expense, income, remittance } = mapBooks((kind) =>
    totals(kind, books[kind]),
  );
  const after = Math.round(income.usd * 100) - Math.round(expense.usd * 100);
  return [
    income.usd,
    expense.usd,
    after / 100,
    remittance.usd,
    (after - Math.round(remittance.usd * 100)) / 100,
    remittance.cny,
  ];
}
// Apply all validated writes together, restoring prior values if a quota error interrupts them.
function commitStorage(changes) {
  const undo = [];
  try {
    for (const [k, value] of changes) {
      const previous = localStorage.getItem(k);
      if (value === null) localStorage.removeItem(k);
      else localStorage.setItem(k, value);
      undo.push([k, previous]);
    }
  } catch (error) {
    for (const [k, old] of undo.reverse()) {
      if (old === null) localStorage.removeItem(k);
      else localStorage.setItem(k, old);
    }
    throw error;
  }
}
export function clearBooks(selected) {
  check(Array.isArray(selected) && selected.length > 0, "请选择要清除的账本。");
  const changes = [];
  for (const kind of new Set(selected)) {
    changes.push([key(kind) + "_before_import", null], [key(kind), null]);
  }
  commitStorage(changes);
}
export function recoverBook(kind, expectedRaw, rows) {
  const value = JSON.stringify(backup(kind, rows).records);
  check(localStorage.getItem(key(kind)) === expectedRaw, "账目已变化，请刷新后重试。");
  commitStorage([[key(kind) + "_damaged", expectedRaw], [key(kind), value]]);
}
export function checkEdit(original, rows) {
  const current = rows.find(row => row.id === original.id);
  check(current, "此记录已删除，请重新打开查看。");
  check(JSON.stringify(current) === JSON.stringify(original), "此记录已在另一页面修改。请保留需要的内容，重新打开这笔记录后再编辑。");
}

// ---------- Excel export, unified with the account ledger format ----------
const bookNames = { expense: "开支", income: "收入", remittance: "汇款" };
const categories = ["购物", "餐饮", "交通", "房屋", "账单", "其它"];
const DETAIL_HEADER = ["日期", "美元", "收付方式", "分类", "汇款类型", "汇率", "人民币", "备注", "记录编号", "版本"];
const cell = (v, s) => ({ v, s });
// Same total-coloring rule as the account export: expenses red, income blue,
// net values colored by sign (negative red, positive blue, zero black), bold.
function paint(role, value) {
  if (typeof value !== "number") return value;
  if (role === "expense") return cell(value, ST.boldRed);
  if (role === "income") return cell(value, ST.boldBlue);
  return cell(value, value < 0 ? ST.boldRed : value > 0 ? ST.boldBlue : ST.boldBlack);
}
function detailSheets(kind, rows) {
  const fx = kind === "remittance";
  // Newest first: by date, then by reverse storage order (records are
  // appended in creation order and carry no creation timestamp).
  const sorted = rows
    .map((row, index) => [row, index])
    .sort((a, b) => b[0].date.localeCompare(a[0].date) || b[1] - a[1])
    .map(([row]) => row);
  const sheets = [];
  for (let offset = 0; offset < Math.max(1, sorted.length); offset += 10000) {
    const suffix = offset ? "-" + (1 + offset / 10000) : "";
    const data = sorted.slice(offset, offset + 10000).map((r) => [
      cell(r.date, ST.date),
      Math.abs(r.amount),
      fx ? "" : r.method === "cash" ? "现金" : "银行卡",
      kind === "expense" ? r.category : "",
      fx ? (r.type === "subtract" || r.amount < 0 ? "冲正" : "汇出") : "",
      fx ? r.rate : "",
      fx ? Math.abs(r.cny) : "",
      r.note,
      r.id,
      "",
    ]);
    sheets.push({
      name: bookNames[kind] + "明细" + suffix,
      rows: [DETAIL_HEADER.map((v) => cell(v, ST.header)), ...data],
      cols: DETAIL_HEADER.map((_, i) => ({
        width: i === 7 ? 32 : 16,
        hidden:
          i >= 8 ||
          (fx
            ? i === 2 || i === 3
            : i === 4 || i === 5 || i === 6 || (kind === "income" && i === 3)),
      })),
      freeze: true,
      validations: fx
        ? [{ ref: "E2:E10001", values: ["汇出", "冲正"] }]
        : kind === "expense"
          ? [
              { ref: "C2:C10001", values: ["现金", "银行卡"] },
              { ref: "D2:D10001", values: categories },
            ]
          : [{ ref: "C2:C10001", values: ["现金", "银行卡"] }],
    });
  }
  return sheets;
}
function groupSums(kind, rows, size) {
  const groups = new Map();
  for (const r of rows) {
    const period = size ? r.date.slice(0, size) : "全部年份";
    const v = groups.get(period) ?? [0, 0, 0, 0, 0];
    v[0]++;
    v[1] += Math.round(r.amount * 100);
    if (kind === "remittance") {
      v[2] += Math.round((r.cny ?? 0) * 100);
      v[3] += Math.abs(r.cny ?? 0);
      v[4] += Math.abs(r.amount);
    } else {
      v[r.method === "cash" ? 2 : 3] += Math.round(r.amount * 100);
    }
    groups.set(period, v);
  }
  return groups;
}
function statsSheet(kind, rows, suffix, size) {
  const fx = kind === "remittance";
  const out = [
    ["期间", "笔数", "美元合计", ...(fx ? ["人民币合计", "平均汇率"] : ["现金", "银行卡"])],
  ];
  for (const [period, v] of [...groupSums(kind, rows, size)].sort().reverse())
    out.push([
      period,
      v[0],
      paint(fx ? "net" : kind, v[1] / 100),
      fx ? paint("net", v[2] / 100) : v[2] / 100,
      fx ? (v[4] ? v[3] / v[4] : 0) : v[3] / 100,
    ]);
  return { name: bookNames[kind] + suffix, rows: out };
}
function overviewSheet(books) {
  const rows = [["账本", "笔数", "美元合计", "人民币合计"]];
  const sums = {};
  for (const kind of kinds) {
    const list = books[kind];
    const usd = list.reduce((n, r) => n + Math.round(r.amount * 100), 0) / 100;
    sums[kind] = usd;
    rows.push([
      bookNames[kind],
      list.length,
      paint(kind === "remittance" ? "net" : kind, usd),
      kind === "remittance"
        ? paint("net", list.reduce((n, r) => n + Math.round((r.cny ?? 0) * 100), 0) / 100)
        : "",
    ]);
  }
  rows.push([
    "汇款后结余",
    "",
    paint("net", Math.round((sums.income - sums.expense - sums.remittance) * 100) / 100),
  ]);
  return { name: "收支汇总", rows };
}
function periodOverview(books, title, size) {
  const periods = new Map();
  for (const kind of kinds)
    for (const r of books[kind]) {
      const period = r.date.slice(0, size);
      const group = periods.get(period) ?? { expense: 0, income: 0, remittance: 0 };
      group[kind] += Math.round(r.amount * 100);
      periods.set(period, group);
    }
  const rows = [["期间", "收入", "开支", "净汇出美元", "汇款后结余"]];
  for (const [period, s] of [...periods].sort(([a], [b]) => b.localeCompare(a)))
    rows.push([
      period,
      paint("income", s.income / 100),
      paint("expense", s.expense / 100),
      paint("net", s.remittance / 100),
      paint("net", (s.income - s.expense - s.remittance) / 100),
    ]);
  return { name: title, rows };
}
function summaryScopeSheet(books) {
  const groups = new Map();
  const total = [0, 0, 0, 0];
  for (const kind of kinds)
    for (const r of books[kind]) {
      const year = r.date.slice(0, 4);
      const sums = groups.get(year) ?? [0, 0, 0, 0];
      const cents = Math.round(r.amount * 100);
      const cny = Math.round((r.cny ?? 0) * 100);
      sums[kinds.indexOf(kind)] += cents;
      total[kinds.indexOf(kind)] += cents;
      sums[3] += cny;
      total[3] += cny;
      groups.set(year, sums);
    }
  groups.set("全部年份合计", total);
  const rows = [
    ["年度", "收入", "生活开支", "扣除开支后剩余", "净汇出美元", "汇款后结余", "汇款折合人民币"],
  ];
  const sorted = [...groups].sort(([a], [b]) =>
    a === "全部年份合计" ? 1 : b === "全部年份合计" ? -1 : b.localeCompare(a),
  );
  for (const [year, [e, i, rm, cny]] of sorted)
    rows.push([
      year,
      paint("income", i / 100),
      paint("expense", e / 100),
      paint("net", (i - e) / 100),
      paint("net", rm / 100),
      paint("net", (i - e - rm) / 100),
      paint("net", cny / 100),
    ]);
  return {
    name: "收支汇总",
    rows,
    cols: Array.from({ length: 7 }, () => ({ width: 20 })),
  };
}
export function reportXlsx(scope, books) {
  if (scope === "summary") return makeWorkbook([summaryScopeSheet(books)]);
  const sheets = [];
  if (scope === "all")
    sheets.push(
      overviewSheet(books),
      periodOverview(books, "月度汇总", 7),
      periodOverview(books, "年度汇总", 4),
    );
  for (const kind of scope === "all" ? kinds : [scope])
    sheets.push(
      statsSheet(kind, books[kind], "汇总", 0),
      statsSheet(kind, books[kind], "月度汇总", 7),
      statsSheet(kind, books[kind], "年度汇总", 4),
      ...detailSheets(kind, books[kind]),
    );
  return makeWorkbook(sheets);
}
